/*
=============================
      LOOPS IN C++
=============================

📌 Definition:
- A loop is used to repeat a block of code multiple times.
- Types: for loop, while loop, do-while loop.

--------------------------------
🔹 FOR LOOP
- Used when number of iterations is known.
Syntax:
    for(initialization; condition; update){
        // code
    }

Example:
    for(int i=1; i<=5; i++){
        cout << i << " ";
    }
Output: 1 2 3 4 5
*/


#include<bits/stdc++.h>
using namespace std;
int main(){
    for(int i=1; i<=10; i++){
        cout << "Hi Dhruv" << endl;
    }
    return 0;
} 